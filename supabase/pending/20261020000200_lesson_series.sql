alter table public.lesson_riders
  add column if not exists horse_id uuid references public.horses (id) on delete set null;
alter table public.lesson_riders
  add column if not exists enrolment_id uuid references public.lesson_enrolments (id) on delete set null;

create index if not exists lesson_riders_enrolment_idx on public.lesson_riders (enrolment_id);
create index if not exists lesson_riders_horse_idx on public.lesson_riders (horse_id);

comment on column public.lesson_riders.horse_id is
  'The horse for THIS occurrence only. Admin-set; a parent cannot change it (guard trigger).';
comment on column public.lesson_riders.enrolment_id is
  'The series that generated this booking, if any. Null for a booking added by hand.';

-- The parent guard, widened to the two new columns. Unchanged otherwise.
create or replace function public.lesson_riders_guard_parent_updates()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_role text;
begin
  if auth.uid() is null then
    return new;
  end if;

  v_role := (select public."current_role"());

  if v_role = 'admin' then
    return new;
  end if;

  if v_role is distinct from 'parent' then
    raise exception 'Only an admin or the rider''s own family may change a booking.'
      using errcode = '42501';
  end if;

  if new.instance_id  is distinct from old.instance_id
     or new.rider_id     is distinct from old.rider_id
     or new.id           is distinct from old.id
     or new.horse_id     is distinct from old.horse_id
     or new.enrolment_id is distinct from old.enrolment_id
  then
    raise exception 'A family may only cancel a booking.'
      using errcode = '42501';
  end if;

  if new.status is distinct from old.status and new.status <> 'cancelled' then
    raise exception 'A family may only cancel a booking. Contact the barn to rebook.'
      using errcode = '42501';
  end if;

  if new.status = 'cancelled' and new.cancelled_at is null then
    new.cancelled_at := now();
  end if;

  return new;
end;
$$;

revoke all on function public.lesson_riders_guard_parent_updates() from public, anon, authenticated;

-- -----------------------------------------------------------------------------
-- book_enrolments(from, through) — book every enrolment into its instances
-- -----------------------------------------------------------------------------
create or replace function public.book_enrolments(
  from_date    date,
  through_date date
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_booked integer := 0;
  r record;
begin
  if (select public."current_role"()) is distinct from 'admin' then
    raise exception 'Only an admin may book enrolments.' using errcode = '42501';
  end if;

  if through_date < from_date then
    return 0;
  end if;

  for r in
    select e.id as enrolment_id, e.rider_id, e.horse_id, li.id as instance_id, li.max_riders
      from public.lesson_enrolments e
      join public.riders rd on rd.id = e.rider_id
      join public.lesson_instances li on li.template_id = e.template_id
     where rd.active
       -- Phase 4 (0026) adds families.status; once applied, also require
       --   and (select f.status from public.families f where f.id = rd.family_id) = 'active'
       and li.status = 'scheduled'
       and li.date between greatest(from_date, e.anchor_date)
                       and least(through_date, coalesce(e.ends_on, through_date))
       and ((li.date - e.anchor_date) % (7 * e.interval_weeks)) = 0
     order by li.date, li.start_time, e.created_at
  loop
    -- Capacity, re-read per row so two enrolments into one instance see each other.
    if (select count(*) from public.lesson_riders lr
         where lr.instance_id = r.instance_id
           and lr.status in ('booked', 'backfilled')) >= r.max_riders then
      continue;
    end if;

    insert into public.lesson_riders (instance_id, rider_id, status, horse_id, enrolment_id)
    values (r.instance_id, r.rider_id, 'booked', r.horse_id, r.enrolment_id)
    on conflict (instance_id, rider_id) do nothing;

    if found then
      v_booked := v_booked + 1;
    end if;
  end loop;

  return v_booked;
end;
$$;

comment on function public.book_enrolments(date, date) is
  'Admin only. Books each active enrolment into the scheduled instances on its cadence, within capacity. Never re-books an existing row, cancelled or not.';

revoke all on function public.book_enrolments(date, date) from public, anon, authenticated;
grant execute on function public.book_enrolments(date, date) to authenticated;

-- Generation books as it goes: generate the instances, then fill them.
create or replace function public.generate_lesson_instances(
  through_date date default (current_date + 28),
  from_date    date default current_date
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_created integer;
begin
  if (select public."current_role"()) is distinct from 'admin' then
    raise exception 'Only an admin may generate lesson instances.' using errcode = '42501';
  end if;

  if through_date < from_date then
    return 0;
  end if;

  insert into public.lesson_instances
    (template_id, date, start_time, duration_min, type, instructor_id, status, level_id, max_riders)
  select t.id, d::date, t.start_time, t.duration_min, t.type, t.instructor_id, 'scheduled',
         t.level_id, t.max_riders
    from public.lesson_templates t
    cross join generate_series(from_date::timestamp, through_date::timestamp, interval '1 day') as d
   where t.active
     and extract(isodow from d) = t.weekday
  on conflict (template_id, date) where template_id is not null do nothing;

  get diagnostics v_created = row_count;

  perform public.book_enrolments(from_date, through_date);

  return v_created;
end;
$$;

revoke all on function public.generate_lesson_instances(date, date) from public, anon, authenticated;
grant execute on function public.generate_lesson_instances(date, date) to authenticated;

-- -----------------------------------------------------------------------------
-- Ending a series, or a rider going inactive, clears FUTURE series bookings
-- -----------------------------------------------------------------------------
create or replace function public.lesson_enrolments_clear_future()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cutoff date;
  v_id     uuid;
begin
  if tg_op = 'DELETE' then
    v_id := old.id;
    v_cutoff := (now() at time zone 'utc')::date;
  else
    if new.ends_on is null or new.ends_on is not distinct from old.ends_on then
      return new;
    end if;
    v_id := new.id;
    v_cutoff := new.ends_on;
  end if;

  delete from public.lesson_riders lr
   using public.lesson_instances li
   where li.id = lr.instance_id
     and lr.enrolment_id = v_id
     and lr.status = 'booked'
     and li.date > v_cutoff;

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

revoke all on function public.lesson_enrolments_clear_future() from public, anon, authenticated;

drop trigger if exists lesson_enrolments_clear_future on public.lesson_enrolments;
create trigger lesson_enrolments_clear_future
  after update of ends_on or delete on public.lesson_enrolments
  for each row execute function public.lesson_enrolments_clear_future();

create or replace function public.riders_clear_future_series()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.active and not new.active then
    delete from public.lesson_riders lr
     using public.lesson_instances li
     where li.id = lr.instance_id
       and lr.rider_id = new.id
       and lr.enrolment_id is not null
       and lr.status = 'booked'
       and li.date > (now() at time zone 'utc')::date;
  end if;
  return new;
end;
$$;

revoke all on function public.riders_clear_future_series() from public, anon, authenticated;

drop trigger if exists riders_clear_future_series on public.riders;
create trigger riders_clear_future_series
  after update of active on public.riders
  for each row execute function public.riders_clear_future_series();

commit;

