--            the enrolment's horse_id and the next week's row are unchanged.
--   deny     parent sets horse_id on their own rider's booking → 42501,
--            re-read unchanged (the guard widening, proved).
--   control  parent cancels one occurrence; regenerate → still cancelled,
--            enrolment_id kept, next week still booked.
--   capacity a third enrolment into a two-seat slot is skipped, not forced.
--   end      ends_on set → future booked rows gone, past + cancelled stay.
--   inactive rider deactivated → future SERIES rows gone, a hand-added
--            future booking stays.
--   definer  book_enrolments is in the entry-point inventory; the three
--            trigger functions are in the internal inventory; anon cannot
--            execute any of them.
-- The cutoff dates use UTC, not the barn's timezone — a known one-day edge at
-- night, same as the existing generator's defaults; the app always passes
-- barn-local dates explicitly to book/generate, and the triggers only ever
-- remove rows strictly AFTER the cutoff, so the edge can only keep a row.
