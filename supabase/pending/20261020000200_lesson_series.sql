-- =============================================================================
-- 0025 — lessons: a horse per occurrence, and recurring enrolment.
--
-- PRINTED FOR AUDIT, NOT APPLIED (2026-10-20). The UI that reads these columns
-- is behind the `lessonSeries` flag (config/barn.ts), false until this is
-- applied, the gate is green, and it has been audited.
--
-- -----------------------------------------------------------------------------
-- 1. A HORSE ON EACH OCCURRENCE — lesson_riders.horse_id
-- -----------------------------------------------------------------------------
-- An occurrence IS a lesson_riders row (one rider, one instance), so the horse
-- lives there. Changing it touches that row and nothing else: the series'
-- usual horse is lesson_enrolments.horse_id, copied onto each row when the
-- row is generated, and never written back. "Swap the horse for one week" and
-- "change the usual horse" are therefore two different writes on two
-- different tables, and the first cannot reach the second by construction.
--
-- THE PARENT GUARD HAD TO BE WIDENED. lesson_riders_guard_parent_updates()
-- lets a parent update their own rider's booking and then checks named
-- columns (instance, rider, id, status). A NEW column is not on that list, so
-- without the change below a parent could set horse_id on their own child's
-- booking over PostgREST — picking the barn's horse for themselves. The guard
-- now refuses any change to horse_id or enrolment_id from a parent.
--
-- -----------------------------------------------------------------------------
-- 2. RECURRING ENROLMENT — lesson_enrolments
-- -----------------------------------------------------------------------------
-- A rider enrols in a recurring slot (a lesson_template) every N weeks:
-- N = 1 weekly, 2 biweekly, anything up to 12 is "custom". Occurrences fall on
-- anchor_date + k·N weeks; anchor_date must be on the template's weekday
-- (enforced by trigger, below). The rider is booked into each generated
-- instance that lands on the cadence, inside [anchor_date, ends_on].
--
-- RLS IN THIS MIGRATION, DEFAULT DENY, TO AUTHENTICATED ONLY:
--   select   admin, staff: all.  client: their own riders (family_owns_rider).
--   insert / update / delete   admin only.
-- Nobody else gets a policy, so signed-out access is nothing.
--
-- WHAT HAPPENS TO FUTURE BOOKINGS
--   enrolment ENDS (ends_on set or moved earlier)
--       every 'booked' row generated by it on a date AFTER ends_on is deleted.
--       Past rows, cancelled rows and backfilled rows are history and stay.
--       Deleted, not cancelled: cancelling fires the family-cancelled
--       notification and opens the seat to backfill, as if the family had
--       released it, which is not what happened.
--   enrolment DELETED
--       same as ending it today; enrolment_id on surviving rows goes null
--       (on delete set null), so the history no longer names a series.
--   rider goes INACTIVE (riders.active true -> false)
--       every future 'booked' row that came FROM A SERIES is deleted. A
--       booking an admin added by hand is left in place — that was a
--       deliberate act on one lesson — and the admin sees it on the day.
--       book_enrolments() skips inactive riders, so nothing new is booked.
--   client goes INACTIVE or ON A BREAK (Phase 4, migration 0026)
--       book_enrolments() is written to skip them once that column exists;
--       see the note in the function.
--
-- A SINGLE CANCELLED OCCURRENCE DOES NOT DETACH FROM THE SERIES. The row
-- keeps its enrolment_id and its status 'cancelled'. The series carries on
-- the next week, and regenerating never re-books the cancelled week, because
-- the row still exists and the booking insert is ON CONFLICT DO NOTHING on
-- the existing (instance_id, rider_id) unique constraint.
--
-- CAPACITY. book_enrolments() books into an instance only while
-- booked + backfilled < max_riders. An enrolment that would overfill is
-- skipped for that week and reported in the return count, never forced in.
--
-- DEFINER FUNCTIONS: every one sets search_path = '', fully qualifies, and
-- gets the three-role revoke. book_enrolments() is the one entry point; it is
-- re-granted to authenticated and gates on admin internally. The trigger
-- functions are revoked from everyone.
--
-- Idempotent throughout: if-not-exists, create-or-replace, drop-if-exists.
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- lesson_enrolments
-- -----------------------------------------------------------------------------
create table if not exists public.lesson_enrolments (
  id              uuid primary key default gen_random_uuid(),
  created_at      timestamptz not null default now(),
  template_id     uuid not null references public.lesson_templates (id) on delete cascade,
  rider_id        uuid not null references public.riders (id) on delete cascade,
  horse_id        uuid references public.horses (id) on delete set null,
  interval_weeks  integer not null default 1 check (interval_weeks between 1 and 12),
  anchor_date     date not null,
  ends_on         date,
  created_by      uuid references public.profiles (id) on delete set null
                    default public.current_profile(),
  constraint lesson_enrolments_ends_after_anchor check (ends_on is null or ends_on >= anchor_date),
  constraint lesson_enrolments_one_per_start unique (template_id, rider_id, anchor_date)
);

alter table public.lesson_enrolments enable row level security;

create index if not exists lesson_enrolments_template_idx on public.lesson_enrolments (template_id);
create index if not exists lesson_enrolments_rider_idx on public.lesson_enrolments (rider_id);

comment on table public.lesson_enrolments is
  'A rider enrolled in a recurring lesson slot every interval_weeks from anchor_date. Admin writes; client reads own riders.';

drop policy if exists "lesson_enrolments: read (barn all, client own riders)" on public.lesson_enrolments;
create policy "lesson_enrolments: read (barn all, client own riders)"
  on public.lesson_enrolments for select to authenticated
  using (
    (select public."current_role"()) in ('admin', 'staff')
    or (select public.family_owns_rider(rider_id))
  );

drop policy if exists "lesson_enrolments: admin insert" on public.lesson_enrolments;
create policy "lesson_enrolments: admin insert"
  on public.lesson_enrolments for insert to authenticated
  with check ((select public."current_role"()) = 'admin');

drop policy if exists "lesson_enrolments: admin update" on public.lesson_enrolments;
create policy "lesson_enrolments: admin update"
  on public.lesson_enrolments for update to authenticated
  using ((select public."current_role"()) = 'admin')
  with check ((select public."current_role"()) = 'admin');

drop policy if exists "lesson_enrolments: admin delete" on public.lesson_enrolments;
create policy "lesson_enrolments: admin delete"
  on public.lesson_enrolments for delete to authenticated
  using ((select public."current_role"()) = 'admin');

-- The anchor must be on the slot's weekday, or "every 2 weeks from the
-- anchor" never lands on an instance and the enrolment silently books nothing.
create or replace function public.lesson_enrolments_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_weekday integer;
begin
  select t.weekday into v_weekday from public.lesson_templates t where t.id = new.template_id;
  if v_weekday is null then
    raise exception 'That lesson slot does not exist.' using errcode = '23503';
  end if;
  if extract(isodow from new.anchor_date) <> v_weekday then
    raise exception 'The first lesson must fall on the slot''s weekday.' using errcode = '23514';
  end if;
  return new;
end;
$$;

revoke all on function public.lesson_enrolments_guard() from public, anon, authenticated;

drop trigger if exists lesson_enrolments_guard on public.lesson_enrolments;
create trigger lesson_enrolments_guard
  before insert or update of template_id, anchor_date on public.lesson_enrolments
  for each row execute function public.lesson_enrolments_guard();

-- -----------------------------------------------------------------------------
-- lesson_riders: the occurrence's horse, and which series made the row
